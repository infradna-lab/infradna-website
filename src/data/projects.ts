export type ProjectMethod = {
  title: string
  desc: string
}

export type MediaItem = {
  /** public/ 기준 경로 또는 import 한 이미지 URL. 예: '/projects/p1-hero.png' */
  src?: string
  /** 이미지 하단 설명 (선택) */
  caption?: string
}

export type Project = {
  id: number
  title: string
  period: string
  category: string
  /** 카드/히어로에 쓰이는 한 줄 요약 */
  summary: string
  /** 연구 개요 (배경·필요성) */
  overview: string
  /** 연구 목표 */
  objectives: string[]
  /** 추진 내용·방법 (단계) */
  methods: ProjectMethod[]
  /** 기대효과 및 활용방안 */
  outcomes: string[]
  /** 사이드 정보 카드 */
  info: {
    organization: string
    support: string
    /** 진척도 0-100 */
    progress: number
  }
  /**
   * 이미지·다이어그램 (선택). 지정하지 않으면 상세 페이지에 자리(placeholder)만 표시됩니다.
   * 이미지는 public/ 폴더에 넣고 '/파일명' 으로 참조하거나 import 해서 넣을 수 있습니다.
   */
  media?: {
    /** 대표 이미지 (히어로 하단 배너) */
    hero?: MediaItem
    /** 추진체계도 */
    diagram?: MediaItem
    /** 연구 성과 이미지들 */
    gallery?: MediaItem[]
  }
}

